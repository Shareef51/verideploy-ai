def generate(write_baseline: bool = False) -> dict[str, Any]:
    OUT.mkdir(parents=True, exist_ok=True)
    schemas: dict[str, dict[str, Any]] = {}
    entries: dict[str, Any] = {}
    for name, model in MODELS.items():
        schema = model.model_json_schema()
        schema["$id"] = f"https://schemas.verideploy.ai/final/{name}.json"
        path = OUT / f"{name}.schema.json"
        path.write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n")
        schemas[name] = schema
        entries[name] = {"file": str(path.relative_to(ROOT)), "sha256": digest(schema), "signature": signature(schema)}
    manifest = {"schema_version": 1, "contract_version": "1.0", "schemas": entries}
    MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    PY_CLIENT.parent.mkdir(parents=True, exist_ok=True); PY_CLIENT.write_text(python_client_text())
    TS_CLIENT.parent.mkdir(parents=True, exist_ok=True); TS_CLIENT.write_text(ts_client_text())
    if write_baseline or not BASELINE.exists():
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        BASELINE.write_text(json.dumps({"contract_version": "1.0", "schemas": {k:v["signature"] for k,v in entries.items()}}, indent=2, sort_keys=True) + "\n")
    return manifest


def validate_compatibility() -> list[str]:
    baseline = json.loads(BASELINE.read_text())
    errors: list[str] = []
    for name, old_sig in baseline["schemas"].items():
        model = MODELS.get(name)
        if model is None:
            errors.append(f"removed schema: {name}")
            continue
        errors.extend(compare_signature(old_sig, signature(model.model_json_schema()), name))
    return errors


if __name__ == "__main__":
    import sys
    write = "--write-baseline" in sys.argv
    generate(write_baseline=write)
    problems = validate_compatibility()
    print(json.dumps({"passed": not problems, "errors": problems}, sort_keys=True))
    raise SystemExit(0 if not problems else 1)
