def canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value)).hexdigest()


def signature(schema: dict[str, Any]) -> dict[str, Any]:
    def node_sig(node: dict[str, Any]) -> dict[str, Any]:
        props = node.get("properties", {})
        out: dict[str, Any] = {
            "required": sorted(node.get("required", [])),
            "properties": {},
        }
        for key in ("type", "format", "$ref", "const"):
            if key in node:
                out[key] = node[key]
        if "enum" in node:
            out["enum"] = sorted(str(x) for x in node["enum"])
        for name, prop in sorted(props.items()):
            item: dict[str, Any] = {}
            for key in ("type", "format", "$ref", "const"):
                if key in prop:
                    item[key] = prop[key]
            if "enum" in prop:
                item["enum"] = sorted(str(x) for x in prop["enum"])
            if "anyOf" in prop:
                item["anyOf"] = sorted(
                    json.dumps({k: branch.get(k) for k in ("type", "format", "$ref", "const") if k in branch}, sort_keys=True)
                    for branch in prop["anyOf"]
                )
            out["properties"][name] = item
        return out

    return {
        "root": node_sig(schema),
        "defs": {name: node_sig(node) for name, node in sorted(schema.get("$defs", {}).items())},
    }


def compare_signature(old: dict[str, Any], new: dict[str, Any], label: str) -> list[str]:
    errors: list[str] = []
    for scope in ("root",):
        o = old.get(scope, {"required": [], "properties": {}})
        n = new.get(scope, {"required": [], "properties": {}})
        for key in ("type", "format", "$ref", "const"):
            if o.get(key) != n.get(key):
                errors.append(f"{label}: incompatible {key} change")
        if "enum" in o and not set(o["enum"]).issubset(set(n.get("enum", []))):
            errors.append(f"{label}: enum values removed")
        old_props, new_props = o["properties"], n["properties"]
        removed = sorted(set(old_props) - set(new_props))
        if removed:
            errors.append(f"{label}: removed properties: {removed}")
        newly_required = sorted(set(n["required"]) - set(o["required"]))
        if newly_required:
            errors.append(f"{label}: newly required properties: {newly_required}")
        for prop in sorted(set(old_props) & set(new_props)):
            before, after = old_props[prop], new_props[prop]
            for key in ("type", "format", "$ref", "const", "anyOf"):
                if before.get(key) != after.get(key):
                    errors.append(f"{label}.{prop}: incompatible {key} change")
            if "enum" in before and not set(before["enum"]).issubset(set(after.get("enum", []))):
                errors.append(f"{label}.{prop}: enum values removed")
    old_defs, new_defs = old.get("defs", {}), new.get("defs", {})
    for def_name in sorted(set(old_defs) - set(new_defs)):
        errors.append(f"{label}: removed definition {def_name}")
    for def_name in sorted(set(old_defs) & set(new_defs)):
        errors.extend(compare_signature({"root": old_defs[def_name]}, {"root": new_defs[def_name]}, f"{label}.$defs.{def_name}"))
    return errors


